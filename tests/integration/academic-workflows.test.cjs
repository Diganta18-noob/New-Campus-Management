const { test } = require('node:test');
const assert = require('node:assert/strict');
const { withTestDatabase } = require('./helpers/testDatabase.cjs');

test('calendar, assessments, support and enrollment enforce scope and capacity', { skip: !process.env.TEST_MONGODB_URI && 'Set TEST_MONGODB_URI to local MongoDB' }, async () => {
  await withTestDatabase(async mongoose => {
    const app = require('../../backend/app');
    const jwt = require('../../backend/node_modules/jsonwebtoken');
    const User = require('../../backend/models/User.model');
    const Batch = require('../../backend/models/Batch.model');
    const Classroom = require('../../backend/models/Classroom.model');
    const Department = require('../../backend/models/Department.model');
    const ids = Array.from({ length: 11 }, () => new mongoose.Types.ObjectId());
    const [admin, trainer, learnerA, learnerB, manager, department, room, batchA, batchB, ta, teamLeader] = ids;
    const previous = process.env.JWT_SECRET;
    process.env.JWT_SECRET = 'academic-workflows-test';
    await User.collection.insertMany([[admin, 'ADMIN'], [trainer, 'TRAINER'], [learnerA, 'LEARNER'], [learnerB, 'LEARNER'], [manager, 'MANAGER'], [ta, 'TA'], [teamLeader, 'TEAM_LEADER']].map(([id, role]) => ({ _id: id, role, firstName: role, lastName: 'Test', email: `${id}@test.local`, username: String(id), isActive: true, assignedBatches: id.equals(learnerA) ? [batchA] : [] })));
    await Department.collection.insertOne({ _id: department, name: 'Department', code: 'D', createdBy: admin });
    await Classroom.collection.insertOne({ _id: room, name: 'Room', code: 'R', location: 'A', capacity: 1, createdBy: admin });
    const baseBatch = { clientName: 'Test', department, startDate: new Date('2026-11-01'), endDate: new Date('2026-11-30'), status: 'ONGOING', classroom: room, trainers: [trainer], tas: [ta], createdBy: admin };
    await Batch.collection.insertMany([{ ...baseBatch, _id: batchA, name: 'A', code: 'A', learners: [learnerA] }, { ...baseBatch, _id: batchB, name: 'B', code: 'B', learners: [] }]);
    const server = app.listen(0, '127.0.0.1');
    await new Promise(resolve => server.once('listening', resolve));
    const base = `http://127.0.0.1:${server.address().port}/api`;
    const call = async (who, method, path, body) => {
      const response = await fetch(base + path, { method, headers: { Authorization: `Bearer ${jwt.sign({ id: String(who) }, process.env.JWT_SECRET)}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
      return { status: response.status, body: await response.json() };
    };
    try {
      const directory = await call(admin, 'GET', '/users?view=directory&role=LEARNER&limit=10');
      assert.equal(directory.status, 200);
      assert.equal(directory.body.data.length, 2);
      assert.equal('assignedBatches' in directory.body.data[0], false);
      assert.equal('tokenVersion' in directory.body.data[0], false);
      const post = await call(admin, 'POST', '/campus-posts', { kind: 'ANNOUNCEMENT', title: 'Batch notice', body: 'Hello', batch: String(batchA) });
      assert.equal(post.status, 201);
      assert.equal((await call(learnerA, 'GET', '/campus-posts')).body.data.length, 1);
      assert.equal((await call(learnerB, 'GET', '/campus-posts')).body.data.length, 0);
      assert.equal((await call(teamLeader, 'GET', '/campus-posts')).body.data.length, 1);
      assert.equal((await call(ta, 'GET', '/campus-posts')).body.data.length, 1);
      assert.equal((await call(learnerB, 'POST', `/campus-posts/${post.body.data._id}/read`)).status, 404);
      assert.equal((await call(learnerA, 'POST', `/campus-posts/${post.body.data._id}/read`)).status, 200);
      assert.equal((await call(learnerA, 'GET', '/campus-posts')).body.unread, 0);
      const scheduled = await call(admin, 'POST', '/campus-posts', { kind: 'EVENT', title: 'Scheduled class', body: 'Lesson', batch: String(batchA), startsAt: '2026-11-02T09:00:00.000Z', endsAt: '2026-11-02T10:00:00.000Z', requiresAttendance: true });
      assert.equal(scheduled.status, 201);
      const queue = await call(admin, 'GET', '/dashboard/operations?startDate=2026-11-01&endDate=2026-11-30');
      assert.equal(queue.status, 200);
      assert.deepEqual(queue.body.data.rows.find(row => row.code === 'A').issues, ['MISSING_ATTENDANCE', 'OVERDUE_UPDATE']);
      const topic = await call(admin, 'POST', '/topics', { name: 'Foundations', batch: String(batchA), startDate: '2026-11-02', endDate: '2026-11-20', trainers: [String(trainer)], tas: [String(ta)] });
      assert.equal(topic.status, 201);
      assert.equal((await call(trainer, 'PATCH', `/topics/${topic.body.data._id}/progress`, { progressPercent: 60, progressNote: 'Six of ten lessons complete' })).status, 200);
      assert.equal((await call(learnerA, 'GET', '/topics')).body.data[0].progressPercent, 60);
      assert.equal((await call(learnerB, 'GET', '/topics')).body.data.length, 0);
      const assessment = await call(trainer, 'POST', '/assessments', { title: 'Test', batch: String(batchA), dueAt: '2026-11-15', maxScore: 100 });
      assert.equal(assessment.status, 201);
      const assessmentId = assessment.body.data._id;
      assert.equal((await call(learnerA, 'GET', '/assessments')).body.data.length, 0);
      assert.equal((await call(trainer, 'PUT', `/assessments/${assessmentId}/results`, { learner: String(learnerB), score: 90 })).status, 400);
      assert.equal((await call(trainer, 'PUT', `/assessments/${assessmentId}/results`, { learner: String(learnerA), score: 85 })).status, 200);
      assert.equal((await call(trainer, 'PATCH', `/assessments/${assessmentId}/publish`, { published: true })).status, 200);
      assert.equal((await call(learnerA, 'GET', '/assessments')).body.data[0].myResult.score, 85);
      const support = await call(learnerA, 'POST', '/support-cases', { batch: String(batchA), subject: 'Help', message: 'Question' });
      assert.equal(support.status, 201);
      assert.equal((await call(learnerB, 'GET', '/support-cases')).body.data.length, 0);
      assert.equal((await call(trainer, 'PATCH', `/support-cases/${support.body.data._id}/status`, { status: 'RESOLVED' })).status, 200);
      assert.equal((await call(learnerB, 'POST', `/support-cases/${support.body.data._id}/replies`, { message: 'No' })).status, 404);
      const requestA = await call(learnerB, 'POST', '/enrollments', { batch: String(batchA) });
      assert.equal(requestA.status, 201);
      assert.equal((await call(admin, 'PATCH', `/enrollments/${requestA.body.data._id}`, { status: 'APPROVED' })).status, 409);
      assert.equal((await call(admin, 'PATCH', `/enrollments/${requestA.body.data._id}`, { status: 'REJECTED' })).status, 200);
      assert.equal((await call(learnerB, 'POST', '/enrollments', { batch: String(batchA) })).status, 201);
      const requestB = await call(learnerB, 'POST', '/enrollments', { batch: String(batchB) });
      assert.equal(requestB.status, 201);
      assert.equal((await call(admin, 'PATCH', `/enrollments/${requestB.body.data._id}`, { status: 'APPROVED' })).status, 200);
      assert.equal((await call(admin, 'PATCH', `/enrollments/${requestB.body.data._id}`, { status: 'APPROVED' })).status, 404);
      assert.equal((await Batch.exists({ _id: batchB, learners: learnerB })) != null, true);
      const learnerC = new mongoose.Types.ObjectId();
      const batchC = new mongoose.Types.ObjectId(), batchD = new mongoose.Types.ObjectId();
      await User.collection.insertOne({ _id: learnerC, role: 'LEARNER', firstName: 'Concurrent', lastName: 'Test', email: 'concurrent@test.local', username: String(learnerC), isActive: true, assignedBatches: [] });
      await Batch.collection.insertMany([{ ...baseBatch, _id: batchC, name: 'C', code: 'C', learners: [] }, { ...baseBatch, _id: batchD, name: 'D', code: 'D', learners: [] }]);
      const [requestC, requestD] = await Promise.all([call(learnerC, 'POST', '/enrollments', { batch: String(batchC) }), call(learnerC, 'POST', '/enrollments', { batch: String(batchD) })]);
      const decisions = await Promise.all([requestC, requestD].map(item => call(admin, 'PATCH', `/enrollments/${item.body.data._id}`, { status: 'APPROVED' })));
      assert.deepEqual(decisions.map(item => item.status).sort(), [200, 409]);
      const enrolled = await Batch.countDocuments({ _id: { $in: [batchC, batchD] }, learners: learnerC });
      assert.equal(enrolled, 1);
      const created = await call(admin, 'POST', '/users', { firstName: 'New', lastName: 'Learner', email: 'new@example.test', username: 'newlearner', role: 'LEARNER' });
      assert.equal(created.status, 201);
      assert.ok(created.body.temporaryPassword.length >= 12);
      assert.equal(created.body.data.requiresPasswordReset, true);
      const imported = await call(admin, 'POST', '/users/bulk', { users: [{ firstName: 'Bulk', lastName: 'Learner', email: 'bulk@example.test', username: 'bulktest', role: 'LEARNER' }] });
      assert.equal(imported.status, 201);
      assert.notEqual(imported.body.data.temporaryCredentials[0].temporaryPassword, created.body.temporaryPassword);
      assert.equal((await call(learnerA, 'GET', '/settings')).status, 403);
      assert.equal((await call(admin, 'PUT', '/settings', { name: 'Test Campus', contactEmail: 'office@example.test', retentionDays: 365 })).status, 200);
      assert.equal((await call(learnerA, 'PUT', '/settings/me', { announcements: false, calendar: true })).status, 200);
      assert.equal((await call(learnerA, 'GET', '/settings/me')).body.data.announcements, false);
      assert.equal((await call(admin, 'GET', '/users?search=.*')).body.total, 0);
      assert.equal((await call(admin, 'GET', '/users?limit=10000')).body.data.length <= 100, true);
      for (const who of [admin, manager, teamLeader, trainer, ta, learnerA]) {
        for (const path of ['/campus-posts', '/assessments', '/support-cases', '/settings/me']) assert.equal((await call(who, 'GET', path)).status, 200);
      }
      for (const who of [manager, teamLeader, trainer, ta]) assert.equal((await call(who, 'GET', '/enrollments')).status, 403);
      assert.equal((await call(learnerA, 'POST', '/assessments', { title: 'No', batch: String(batchA), dueAt: '2026-11-15', maxScore: 10 })).status, 403);
    } finally { await new Promise(resolve => server.close(resolve)); process.env.JWT_SECRET = previous; }
  });
});
